# Ciclo/Bucle WHILE (mientras)
# Un ciclo es un BUCLE que se esta repitiendo en base a ciertas condiciones logicas
# Cada repetición se llama ITERACIÓN

#Un ciclo while permite ralizar una serie de acciones posteriores a la validadción de la condición logica

Contador = 0

while Contador <= 10:
    print(f'valor contador {Contador}')
    #Contador = Contador + 1
    Contador += 1 #es lo mismo que el anterior pero mas resumido