# Operador EQUIVALENTE
print('Operador EQUIVALENTE')
print(f'5 == 6? {5 == 6}')
print(f'3 == 9/3? {3 == 9/3}')

# Operador MAYOR QUE
print(f'6 > 9? {6 > 9}')
print(f'0 > 3? {0 > 3}')

# Operador MAYOR O IGUAL QUE
print(f'6 >= 9? {6 >= 9}')
print(f'6 >= 12/2? {6 >= 12/2}')

# Operador MENOR QUE
print(f'6 < 9? {6 < 9}')
print(f'0 < 3? {0 < 3}')

# Operador MENOR O IGUAL QUE
print(f'6 <= 9? {6 <= 9}')
print(f'6 <= 12/2? {6 <= 12/2}')


